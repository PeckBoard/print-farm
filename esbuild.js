// Two-stage bundle (same shape as graphify / chicken-coop).
//
// Stage 1 compiles the browser page (ui/main.ts, three.js included) into one
// minified IIFE and writes it into src/generated/pageBundle.ts as a
// JSON-escaped string constant, which src/page.ts splices into the served
// HTML. Bundling (not a CDN) keeps the page working offline and independent of
// whatever CSP the host frames it with.
//
// Stage 2 is the standard plugin bundle: one CommonJS es2020 file that the
// Extism js-pdk compiler (`extism-js`) turns into the wasm plugin.
//
// `node esbuild.js --page` runs stage 1 only (npm test needs the generated
// module but not the plugin bundle).
const esbuild = require("esbuild");
const fs = require("fs");

async function main() {
  const page = await esbuild.build({
    entryPoints: ["ui/main.ts"],
    bundle: true,
    minify: true,
    format: "iife",
    target: ["es2020"],
    write: false,
    logLevel: "info",
  });
  // A literal "</script" inside the bundle would close the inline <script>.
  const js = page.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
  fs.mkdirSync("src/generated", { recursive: true });
  fs.writeFileSync(
    "src/generated/pageBundle.ts",
    "// GENERATED by esbuild.js (stage 1) — do not edit, not committed.\n" +
      "export const PAGE_JS: string = " +
      JSON.stringify(js) +
      ";\n",
  );
  if (process.argv.includes("--page")) return;

  await esbuild.build({
    entryPoints: ["src/index.ts"],
    outfile: "dist/index.js",
    bundle: true,
    sourcemap: false,
    minify: false,
    format: "cjs",
    target: ["es2020"],
    logLevel: "info",
  });
}

main().catch(() => process.exit(1));
